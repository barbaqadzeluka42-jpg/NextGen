// Concatenates supabase/migrations/*.sql into supabase/setup.sql (one paste into the Supabase SQL Editor).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../supabase/migrations/", import.meta.url);
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
const out = files.map((f) => `-- ════════ ${f} ════════\n${readFileSync(new URL(f, dir), "utf8")}`).join("\n\n");
writeFileSync(new URL("../supabase/setup.sql", import.meta.url), `-- GENERATED by \`npm run db:bundle\` – do not edit; edit supabase/migrations/* instead.\n\n${out}`);
console.log(`supabase/setup.sql ← ${files.join(", ")}`);
